import assert from "node:assert/strict";
import { createExamState, calculateNativeStaminaDamage, markNativeStatusTurnStart, tickNativeScoreTimedStatuses } from "../web/exam_effects.js";
import { NATIVE_EFFECT_EXECUTOR_CLASSES as classes, NATIVE_MASTER_EFFECT_EXECUTOR_CLASSES as masters } from "../web/tower_runtime.js";
const ctor=classes.StaminaReduceChangeEffectExecutor;
assert.equal(masters.ExamStaminaReduceChange,ctor);
const exam=createExamState({stamina:20,maxStamina:20});
exam.runtimeSettings={...(exam.runtimeSettings??{}),examStaminaReduceChange:1};
assert.equal(calculateNativeStaminaDamage(exam,2).damage,2);
const event={effects:[]};
ctor.ExecuteEffect({exam,v1:3,v2:2,event});
assert.equal(exam.staminaReduceChange,3);
assert.equal(calculateNativeStaminaDamage(exam,2).damage,1);
assert.equal(calculateNativeStaminaDamage(exam,4).damage,4);
markNativeStatusTurnStart(exam);
tickNativeScoreTimedStatuses(exam);
assert.equal(exam.staminaReduceChange,3);
tickNativeScoreTimedStatuses(exam);
assert.equal(exam.staminaReduceChange,0);
assert.equal(calculateNativeStaminaDamage(exam,2).damage,2);
assert.equal(event.effects.length,1);
console.log("native stamina reduce change threshold and turn expiration: OK");
